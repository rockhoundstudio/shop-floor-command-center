export function isCanonicalCapabilityField(field) {
  if (!field) return false;
  return (
    field.registryRole === "PRIMARY_CANDIDATE_DESTINATION" ||
    field.registryRole === "APPROVED_MEASUREMENT_ADDITION"
  );
}

